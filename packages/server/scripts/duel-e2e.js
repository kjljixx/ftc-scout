const { io } = require("../../../node_modules/socket.io-client");
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const team = (number, name) => ({ number, name, city: "", state: "", country: "", seasons: [2025] });
const connect = () => new Promise((res) => { const s = io("http://localhost:4000", { path: "/socket.io" }); s.on("connect", () => res(s)); });
const ask = (s, ev, ...a) => s.timeout(8000).emitWithAck(ev, ...a);
(async () => {
  const [a, b] = [await connect(), await connect()];
  const pair = { mode: "custom", steps: null, start: team(23273, "Salisbury Robotics Black"), destination: team(28675, "BrainPower") };
  const created = await ask(a, "create", pair);
  const joined = await ask(b, "join", created.code);
  const views = { a: null, b: null };
  a.on("state", (v) => (views.a = v)); b.on("state", (v) => (views.b = v));
  await ask(a, "start", { code: created.code, token: created.token });
  await wait(3500);
  const ca = { code: created.code, token: created.token }, cb = { code: created.code, token: joined.token };
  const best = await (await fetch("http://localhost:4000/rest/v1/game/solve?from=23273&to=28675")).json();
  const step = best.path[1];
  const hop = await ask(b, "hop", cb, { number: step.number, name: step.name, hop: { ...step.hop, kind: "match" } });
  console.log("b hop to", step.number, hop);
  const cast = await ask(a, "sabotage", ca, "disorient", null);
  console.log("a disorient", cast);
  await wait(500);
  const mine = views.b.mine;
  console.log("b incoming", JSON.stringify(mine.incoming), "hops", views.b.players[1].hops);
  const again = await ask(a, "sabotage", ca, "disorient", null);
  console.log("second cast", again);
  const landed = mine.incoming[0];
  const next = best.path[2];
  const hop2 = await ask(b, "hop", cb, { number: next.number, name: next.name, hop: { ...next.hop, kind: "match" } });
  console.log("b hop to best[2] from landing (expect rejected unless adjacent)", landed.team, hop2);
  await ask(b, "giveUp", cb);
  await wait(500);
  console.log("end paths b", JSON.stringify(views.a.paths?.[1]?.map((s) => ({ n: s.number, sab: s.sabotages }))));
  console.log("end paths a", JSON.stringify(views.a.paths?.[0]?.map((s) => ({ n: s.number, sab: s.sabotages }))));
  a.close(); b.close(); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
